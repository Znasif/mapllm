#!/usr/bin/env node
/**
 * Headless checks for `src/lib/parity/toolEval.js`.
 *
 * Two jobs. First, prove the GRADER against fabricated model responses — if the
 * grader is wrong every number the benchmark ever prints is wrong, and that is
 * exactly the failure you cannot spot by reading a results table.
 *
 * Second, compile every real case from the generated Audiom dataset through the
 * real `candidateContext` + `toolFilter`. That catches the benchmark rotting
 * against the schema — a renamed capability or a dropped profile breaks
 * compilation here rather than silently offering the model a shorter tool list
 * and scoring the result as a model regression.
 *
 * The dataset is `docs/eval_dataset_empire_state.json`, generated by
 * `scripts/gen_eval_cases.mjs` from a live Audiom read. Nothing here may assume
 * a fixed case count or a hand-authored id: regenerating for another map must
 * not break the tests.
 *
 * No LLM, no server, no network.
 */

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  PROFILE_FRAMES, compileCase, expectedPlace, extractCall, formatEvalReport,
  gradeCase, gradeRetrieval, summarise,
} from '../src/lib/parity/toolEval.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const DATASET = process.env.EVAL_DATASET || 'docs/eval_dataset_empire_state.json';
const dataset = JSON.parse(readFileSync(join(root, DATASET), 'utf-8'));
const schema = JSON.parse(readFileSync(join(root, 'docs/llm-tools.schema.json'), 'utf-8'));

let pass = 0;
let fail = 0;
const check = (name, cond, extra = '') => {
  if (cond) { pass += 1; console.log(`  ok   ${name}`); }
  else { fail += 1; console.log(`  FAIL ${name}${extra ? ` — ${extra}` : ''}`); }
};
const eq = (name, a, b) => check(name, JSON.stringify(a) === JSON.stringify(b),
  `got ${JSON.stringify(a)}, want ${JSON.stringify(b)}`);

const call = (name, args) => ({
  tool_calls: [{ function: { name, arguments: JSON.stringify(args) } }],
});

console.log('\nextractCall');
{
  eq('no call', extractCall({ content: 'hello' }),
    { calledTool: null, calledArgs: null, argsError: null });
  eq('null message', extractCall(null), { calledTool: null, calledArgs: null, argsError: null });
  eq('simple call', extractCall(call('whats_here', {})),
    { calledTool: 'whats_here', calledArgs: {}, argsError: null });
  eq('call with args', extractCall(call('get_place_details', { place: 'The Grand Hotel' })),
    { calledTool: 'get_place_details', calledArgs: { place: 'The Grand Hotel' }, argsError: null });
  eq('empty argument string means no args', extractCall({
    tool_calls: [{ function: { name: 'whats_here', arguments: '' } }],
  }), { calledTool: 'whats_here', calledArgs: {}, argsError: null });

  // Some transports hand back an already-parsed object rather than a string.
  eq('pre-parsed object arguments', extractCall({
    tool_calls: [{ function: { name: 'am_i_at', arguments: { place: 'X' } } }],
  }), { calledTool: 'am_i_at', calledArgs: { place: 'X' }, argsError: null });

  const bad = extractCall({ tool_calls: [{ function: { name: 'route_to', arguments: '{oops' } }] });
  check('broken json reports the tool', bad.calledTool === 'route_to');
  check('broken json reports an error', typeof bad.argsError === 'string' && bad.argsError.length > 0);
  check('broken json yields no args', bad.calledArgs === null);

  // toolLoop.js reads tool_calls, not finish_reason — a truncated round can
  // report `length` and still carry a complete call.
  eq('finish_reason is irrelevant', extractCall({ ...call('whats_here', {}), finish_reason: 'length' }).calledTool,
    'whats_here');
}

console.log('\ngradeCase — positive cases');
{
  const tc = { expected_tool: 'get_place_details', expected_args: { place: 'The Grand Hotel' } };
  eq('exact hit', gradeCase(tc, { calledTool: 'get_place_details', calledArgs: { place: 'The Grand Hotel' } }),
    { toolMatch: true, argsMatch: true, falsePositive: false, correct: true });
  eq('right tool, wrong args', gradeCase(tc, { calledTool: 'get_place_details', calledArgs: { place: 'Big Screen Plaza' } }),
    { toolMatch: true, argsMatch: false, falsePositive: false, correct: false });
  eq('wrong tool', gradeCase(tc, { calledTool: 'whats_here', calledArgs: {} }),
    { toolMatch: false, argsMatch: false, falsePositive: false, correct: false });
  eq('no call at all', gradeCase(tc, { calledTool: null, calledArgs: null }),
    { toolMatch: false, argsMatch: false, falsePositive: false, correct: false });

  // Subset comparison, matching eval_tools.py:407 — extra keys are permitted.
  const extra = gradeCase(tc, {
    calledTool: 'get_place_details', calledArgs: { place: 'The Grand Hotel', verbosity: 'long' },
  });
  check('extra args are not penalised', extra.correct === true);

  // `expected_args: null` means any arguments are acceptable (P02).
  const anyArgs = { expected_tool: 'describe_surroundings', expected_args: null };
  check('null expected_args accepts args', gradeCase(anyArgs,
    { calledTool: 'describe_surroundings', calledArgs: { radius: 50 } }).correct === true);
  check('null expected_args accepts none', gradeCase(anyArgs,
    { calledTool: 'describe_surroundings', calledArgs: {} }).correct === true);
}

console.log('\ngradeCase — refusal cases (expected_tool: null)');
{
  const tc = { expected_tool: null, expected_args: null };
  eq('held the line', gradeCase(tc, { calledTool: null }),
    { toolMatch: true, argsMatch: true, falsePositive: false, correct: true });
  eq('called anything = false positive', gradeCase(tc, { calledTool: 'whats_here', calledArgs: {} }),
    { toolMatch: false, argsMatch: false, falsePositive: true, correct: false });
  check('a missing expected_tool key behaves as null',
    gradeCase({}, { calledTool: null }).correct === true);
}

console.log('\nsummarise');
{
  const results = [
    { id: 'a', profile: 'osm_full', expectedTool: 'whats_here', toolMatch: true, argsMatch: true, correct: true, falsePositive: false },
    { id: 'b', profile: 'osm_full', expectedTool: 'route_to', toolMatch: true, argsMatch: false, correct: false, falsePositive: false },
    { id: 'c', profile: 'camio', expectedTool: null, toolMatch: false, argsMatch: false, correct: false, falsePositive: true },
    { id: 'd', profile: 'camio', expectedTool: null, toolMatch: true, argsMatch: true, correct: true, falsePositive: false },
  ];
  const s = summarise(results);
  eq('counts', [s.cases, s.correct, s.toolMatch, s.argsMatch, s.falsePositives], [4, 2, 3, 2, 1]);
  eq('refusals', [s.refusalCases, s.refusalsHeld], [2, 1]);
  check('accuracy', Math.abs(s.accuracy - 0.5) < 1e-9);
  eq('by profile', s.byProfile, { osm_full: { cases: 2, correct: 1 }, camio: { cases: 2, correct: 1 } });
  check('empty input does not divide by zero', summarise([]).accuracy === 0);

  // A transport failure is not a wrong answer AND not a right one. Folding
  // errors into `correct` would make a server outage look like a good run.
  const withErrors = [
    { id: 'e1', profile: 'osm_full', expectedTool: 'whats_here', toolMatch: false, argsMatch: false, correct: false, falsePositive: false, error: 'ECONNREFUSED' },
    { id: 'e2', profile: 'osm_full', expectedTool: 'whats_here', toolMatch: true, argsMatch: true, correct: true, falsePositive: false, error: null },
  ];
  const es = summarise(withErrors);
  eq('errors counted separately', [es.cases, es.correct, es.errors], [2, 1, 1]);
  check('errors do not inflate accuracy', Math.abs(es.accuracy - 0.5) < 1e-9, String(es.accuracy));
  check('an all-error run scores zero',
    summarise([{ id: 'x', profile: 'osm_full', expectedTool: 'whats_here', correct: false, error: 'boom' }]).accuracy === 0);
  check('report surfaces the error count',
    formatEvalReport(withErrors).includes('failed to run at all'));
  check('argsErrors counted', summarise([{ id: 'a', profile: 'osm_full', expectedTool: 'route_to', correct: false, argsError: 'bad json' }]).argsErrors === 1);
}

console.log('\nformatEvalReport');
{
  const results = [
    { id: 'P01', profile: 'osm_full', expectedTool: 'whats_here', calledTool: 'whats_here', calledArgs: {}, toolMatch: true, argsMatch: true, correct: true, falsePositive: false },
    { id: 'P03', profile: 'osm_full', expectedTool: 'get_place_details', calledTool: 'whats_here', calledArgs: {}, toolMatch: false, argsMatch: false, correct: false, falsePositive: false },
  ];
  const text = formatEvalReport(results, { label: 'unit' });
  check('headline count', text.includes('1/2 correct'));
  check('lists the miss', text.includes('P03'));
  const missIdx = text.indexOf('MISSES');
  const profIdx = text.indexOf('by profile');
  check('misses come before the by-profile footer', missIdx >= 0 && missIdx < profIdx);
  check('names the failure mode', text.includes('wrong tool'));
  check('flags uncovered profiles', text.includes('NOT COVERED'));
  check('names an uncovered profile', text.includes('audiom_tier_a'));

  const clean = formatEvalReport([{ id: 'x', profile: 'osm_full', expectedTool: 'whats_here', calledTool: 'whats_here', toolMatch: true, argsMatch: true, correct: true, falsePositive: false }]);
  check('clean run says so', clean.includes('No misses.'));
}

console.log('\nthe real dataset compiles through the real modules');
{
  check('the dataset has cases', dataset.length > 0, `got ${dataset.length}`);
  check('every case is Audiom-generated',
    dataset.every((c) => typeof c.generated_from === 'string' && c.generated_from.startsWith('audiom:')),
    JSON.stringify([...new Set(dataset.map((c) => c.generated_from))]));
  const cache = new Map();
  let compiled = 0;
  for (const tc of dataset) {
    const c = compileCase(schema, tc, { toolCache: cache });
    if (!c.systemPrompt || !c.userMessage || !Array.isArray(c.tools)) {
      check(`${tc.id} compiles`, false, JSON.stringify(c).slice(0, 120));
      continue;
    }
    compiled += 1;
  }
  check('every case compiles', compiled === dataset.length, `${compiled}/${dataset.length}`);

  // Tool filtering is a property of the SCHEMA, not of whichever dataset is
  // loaded. Driving it from the dataset only worked while the dataset happened
  // to span five profiles; the generated Audiom sets are single-profile, and a
  // check that silently becomes vacuous is worse than no check.
  const byProfile = new Map();
  for (const profile of Object.keys(schema.capabilityProfiles || {}).filter((x) => !x.startsWith('$'))) {
    const probe = { id: `probe-${profile}`, capability_profile: profile, utterance: 'what is here?' };
    byProfile.set(profile, compileCase(schema, probe, { toolCache: cache }).tools.length);
  }
  check('every profile offers at least one tool',
    [...byProfile.values()].every((n) => n > 0), JSON.stringify([...byProfile]));
  check('profiles differ in what they offer',
    new Set(byProfile.values()).size > 1, JSON.stringify([...byProfile]));
  check('the dataset\'s own profile is among them',
    dataset.every((tc) => byProfile.has(tc.capability_profile)),
    JSON.stringify([...new Set(dataset.map((t) => t.capability_profile))]));

  // The utterance must reach the model, and a case with resolved places must
  // carry them — otherwise get_place_details cannot possibly be graded fairly.
  const withPlace = dataset.find((t) => t.expected_args?.place && (t.context?.resolved_places || []).length > 1);
  check('the dataset has a case with distractors', Boolean(withPlace));
  const compiledPlace = compileCase(schema, withPlace, { toolCache: cache });
  check('utterance is in the user turn', compiledPlace.userMessage.includes(withPlace.utterance));
  // Probe with a DISTRACTOR, not the answer: the answer's name is in the
  // utterance itself, so it proves nothing about the candidate block.
  const distractor = withPlace.context.resolved_places.find((n) => n !== withPlace.expected_args.place);
  check('resolved places reach the user turn', compiledPlace.userMessage.includes(distractor),
    `distractor=${distractor}`);

  check('unknown profile throws', (() => {
    try { compileCase(schema, { id: 'z', capability_profile: 'nope', utterance: 'hi' }); return false; }
    catch { return true; }
  })());

  // A perfect oracle must score 21/21; if it does not, the grader and the
  // dataset disagree about something and no real number can be trusted.
  const oracle = dataset.map((tc) => ({
    ...gradeCase(tc, tc.expected_tool === null
      ? { calledTool: null, calledArgs: null }
      : { calledTool: tc.expected_tool, calledArgs: tc.expected_args ?? {} }),
    id: tc.id,
    profile: tc.capability_profile,
    expectedTool: tc.expected_tool ?? null,
  }));
  const os = summarise(oracle);
  check('a perfect responder scores 100%', os.correct === dataset.length, `${os.correct}/${dataset.length}`);
  check('and trips no false positives', os.falsePositives === 0);

  // …and a responder that always calls whats_here must NOT score well, or the
  // grader is not discriminating.
  const lazy = dataset.map((tc) => ({
    ...gradeCase(tc, { calledTool: 'whats_here', calledArgs: {} }),
    id: tc.id, profile: tc.capability_profile, expectedTool: tc.expected_tool ?? null,
  }));
  const ls = summarise(lazy);
  const refusals = dataset.filter((t) => (t.expected_tool ?? null) === null).length;
  check('a lazy responder scores badly', ls.correct <= 3, `got ${ls.correct}`);
  check('and is caught making a false positive per refusal case',
    ls.falsePositives === refusals, `${ls.falsePositives} vs ${refusals} refusals`);
}

console.log('\nl1 retrieval is graded separately');
{
  const needsPlace = { id: 'P03', expected_tool: 'get_place_details', expected_args: { place: 'The Grand Hotel' } };
  const noPlace = { id: 'P01', expected_tool: 'whats_here', expected_args: {} };

  eq('expectedPlace reads expected_args', expectedPlace(needsPlace), 'The Grand Hotel');
  eq('expectedPlace is null when none is needed', expectedPlace(noPlace), null);
  eq('expectedPlace tolerates a missing block', expectedPlace({}), null);

  eq('hit at rank 1', gradeRetrieval(needsPlace, ['The Grand Hotel', 'Big Screen Plaza']),
    { applicable: true, hit: true, rank: 1, wanted: 'The Grand Hotel' });
  eq('hit at rank 3', gradeRetrieval(needsPlace, ['Big Screen Plaza', 'Broadway', 'The Grand Hotel']),
    { applicable: true, hit: true, rank: 3, wanted: 'The Grand Hotel' });
  eq('miss', gradeRetrieval(needsPlace, ['Big Screen Plaza', 'Broadway']),
    { applicable: true, hit: false, rank: null, wanted: 'The Grand Hotel' });
  eq('empty retrieval is a miss, not n/a', gradeRetrieval(needsPlace, []),
    { applicable: true, hit: false, rank: null, wanted: 'The Grand Hotel' });
  eq('accepts {name} objects', gradeRetrieval(needsPlace, [{ name: 'The Grand Hotel' }]).hit, true);

  // The load-bearing one: a case that needs no place must be n/a, never a hit.
  eq('no place needed = not applicable', gradeRetrieval(noPlace, []),
    { applicable: false, hit: null, rank: null, wanted: null });

  // …and summarise must not average n/a cases into recall, or an index that
  // returns nothing scores well on a dataset where most cases take no args.
  const mixed = [
    { id: 'a', profile: 'osm_full', expectedTool: 'whats_here', correct: true, retrieval: { applicable: false, hit: null } },
    { id: 'b', profile: 'osm_full', expectedTool: 'whats_here', correct: true, retrieval: { applicable: false, hit: null } },
    { id: 'c', profile: 'osm_full', expectedTool: 'get_place_details', correct: false, retrieval: { applicable: true, hit: false, wanted: 'The Grand Hotel' } },
    { id: 'd', profile: 'osm_full', expectedTool: 'get_place_details', correct: true, retrieval: { applicable: true, hit: true } },
  ];
  const ms = summarise(mixed);
  eq('recall counted over applicable cases only', [ms.retrievalCases, ms.retrievalHits], [2, 1]);
  const text = formatEvalReport(mixed);
  check('report states L1 recall', text.includes('L1 recall 1/2'));
  check('an L1 miss is attributed to L1, not to tool choice',
    text.includes('L1 MISS') && text.includes('The Grand Hotel'));

  // compileCase must actually use injected candidates instead of the dataset's.
  const p03 = dataset.find((t) => t.expected_args?.place && (t.context?.resolved_places || []).length > 1);
  const withL1 = compileCase(schema, p03, { candidates: ['Retrieved Place A', 'Retrieved Place B'] });
  check('injected candidates reach the prompt', withL1.userMessage.includes('Retrieved Place A'));
  // Probe with a DISTRACTOR, not the answer: P03's utterance is "Tell me about
  // The Grand Hotel", so that name is in the message whatever the candidates are.
  // "Cafe R" appears only in resolved_places, so it isolates the candidate block.
  const dis = p03.context.resolved_places.find((n) => n !== p03.expected_args.place);
  check('dataset candidates are NOT used when overridden', !withL1.userMessage.includes(dis));
  const withDataset = compileCase(schema, p03, {});
  check('dataset candidates used by default', withDataset.userMessage.includes(dis));
  check('an empty candidate list is honoured, not ignored',
    !compileCase(schema, p03, { candidates: [] }).userMessage.includes(dis));
  check('the utterance survives either way',
    withL1.userMessage.includes(p03.utterance) && withDataset.userMessage.includes(p03.utterance));
}

console.log('\nprofile frames');
{
  // `$`-prefixed keys are JSON-schema annotations ($comment), not profiles.
  const schemaProfiles = Object.keys(schema.capabilityProfiles || {}).filter((p) => !p.startsWith('$'));
  check('the schema declares profiles', schemaProfiles.length >= 5, JSON.stringify(schemaProfiles));
  check('every profile in the schema has a frame',
    schemaProfiles.every((p) => PROFILE_FRAMES[p]),
    JSON.stringify(schemaProfiles.filter((p) => !PROFILE_FRAMES[p])));
  check('every frame maps to a real profile',
    Object.keys(PROFILE_FRAMES).every((p) => schemaProfiles.includes(p)),
    JSON.stringify(Object.keys(PROFILE_FRAMES).filter((p) => !schemaProfiles.includes(p))));
  eq('frames match eval_tools.py', PROFILE_FRAMES, {
    osm_full: 'geographic',
    osm_places_only: 'geographic',
    audiom_tier_a: 'enu',
    audiom_tier_c: 'enu',
    camio: 'image',
  });
}

console.log(`\n${pass} passed, ${fail} failed`);
if (fail === 0) console.log('ALL PASS');
process.exit(fail === 0 ? 0 : 1);
